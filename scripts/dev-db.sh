#!/usr/bin/env bash
# Throwaway PostgreSQL 16 in Docker for local development, without Kubernetes.
#   scripts/dev-db.sh up     start the container, create the database and the four roles with
#                            `proretactl db bootstrap` (credentials go to .dev/db.secret instead of
#                            a Kubernetes Secret) and write .dev/env for the Makefile dev-* targets
#   scripts/dev-db.sh down   remove the container and the .dev directory
# Optional environment: DEV_DB_PORT (default 55432), DEV_ADMIN_PASSWORD (the first admin's password,
# default a random one), DEV_WEB_PORT (the web dev server, default 5173; it is part of the public URL).
set -euo pipefail

cd "$(dirname "$0")/.."
root=$PWD
name=proreta-dev-db
port=${DEV_DB_PORT:-55432}
web_port=${DEV_WEB_PORT:-5173}
dev=$root/.dev

case ${1:-} in
  up) ;;
  down)
    docker rm -f -v "$name" >/dev/null 2>&1 || true
    rm -rf "$dev"
    echo "removed container $name and $dev"
    exit 0
    ;;
  *)
    echo "usage: $0 up|down" >&2
    exit 2
    ;;
esac

if [ -e "$dev/env" ] || docker container inspect "$name" >/dev/null 2>&1; then
  echo "already set up (container $name or $dev/env exists); run '$0 down' first for a fresh start" >&2
  exit 1
fi

rand() { openssl rand -base64 "$1" | tr -d '\n'; }
ctl() { (cd backend && go run ./cmd/proretactl "$@"); }

admin_pw=$(openssl rand -hex 16)
mkdir -p "$dev"
chmod 700 "$dev"

docker run -d --name "$name" -e POSTGRES_PASSWORD="$admin_pw" -p "127.0.0.1:$port:5432" postgres:16 >/dev/null
echo "waiting for PostgreSQL on 127.0.0.1:$port"
for _ in $(seq 1 60); do
  # The image restarts once after initialising; wait for a query to work over TCP.
  if docker exec "$name" psql -h 127.0.0.1 -U postgres -tAc 'select 1' >/dev/null 2>&1; then ready=1; break; fi
  sleep 1
done
[ "${ready:-}" = 1 ] || { echo "PostgreSQL did not become ready" >&2; docker logs "$name" >&2; exit 1; }

PRORETA_BOOTSTRAP_HOST=127.0.0.1 PRORETA_BOOTSTRAP_PORT=$port \
  PRORETA_BOOTSTRAP_ADMIN_USER=postgres PRORETA_BOOTSTRAP_ADMIN_PASSWORD=$admin_pw \
  PRORETA_BOOTSTRAP_SSLMODE=disable PRORETA_BOOTSTRAP_SECRET_FILE=$dev/db.secret \
  ctl db bootstrap

secret() { sed -n "s/^$1=//p" "$dev/db.secret"; }

login_pw=${DEV_ADMIN_PASSWORD:-$(openssl rand -hex 12)}
hash=$(printf '%s\n' "$login_pw" | ctl hashpw)
umask 077
printf 'login: admin\npassword: %s\n' "$login_pw" >"$dev/admin-login"
cat >"$dev/env" <<ENV
# Generated by scripts/dev-db.sh; sourced by the Makefile dev-* targets. Local development only.
PRORETA_PUBLIC_URL='http://localhost:$web_port'
PRORETA_WEB_PORT='$web_port'
PRORETA_COOKIE_SECURE='false'
PRORETA_ADMIN_LOGIN='admin'
PRORETA_ADMIN_PASSWORD_HASH='$hash'
PRORETA_ENCRYPTION_KEYS='{"k1":"$(rand 32)"}'
PRORETA_ENCRYPTION_ACTIVE_KEY_ID='k1'
PRORETA_STATUSPAGE_COOKIE_KEY='$(rand 32)'
DEV_OWNER_URL='$(secret owner_url)'
DEV_API_URL='$(secret api_url)'
DEV_WORKER_URL='$(secret worker_url)'
DEV_STATUSPAGE_URL='$(secret statuspage_url)'
ENV

cat <<MSG

Database ready on 127.0.0.1:$port (container $name). Settings: .dev/env
First admin: login 'admin', password in .dev/admin-login
Next: make dev-migrate, then make -j5 -O dev-api dev-worker dev-jobs dev-statuspage dev-web
MSG
