package api

import (
	"flag"
	"fmt"
	"os"
	"sort"
	"strings"
	"testing"

	"github.com/proreta-io/proreta/backend/internal/authz"
)

const rolesDocPath = "../../../docs/roles.md"

var updateRolesDoc = flag.Bool("update", false, "rewrite docs/roles.md from the authorization tables")

func rolesDoc(t *testing.T) string {
	t.Helper()
	_, ops := specOperations(t)
	sort.Slice(ops, func(i, j int) bool {
		if ops[i].path != ops[j].path {
			return ops[i].path < ops[j].path
		}
		return ops[i].method < ops[j].method
	})
	var b strings.Builder
	b.WriteString("# Roles and permissions\n\n")
	b.WriteString("<!-- Generated by `go test ./internal/api -run TestRolesDoc -update` in backend/. Do not edit. -->\n\n")
	b.WriteString("What each role may do. Every API operation needs one permission; a role is a set of permissions.\n")
	b.WriteString("The same four roles exist on the organization and on a project. A role on the organization applies to every project; a direct role on a project applies to that project only; the role in a project is the higher of the two.\n")
	b.WriteString("Permissions of the `organization` level are held only through an organization role, so a person without one (who belongs to the organization only through projects) never holds them. `project` permissions are judged per project with that role. The `account` level is the person's own session and organizations and is held by everybody who belongs to the organization.\n\n")
	b.WriteString("## Roles and permissions\n\n| Permission | Level | What it allows |")
	for _, r := range authz.Roles() {
		fmt.Fprintf(&b, " %s |", r)
	}
	b.WriteString("\n|---|---|---|")
	for range authz.Roles() {
		b.WriteString("---|")
	}
	b.WriteString("\n")
	for _, d := range authz.Permissions() {
		fmt.Fprintf(&b, "| `%s` | %s | %s |", d.Name, d.Level, d.Description)
		for _, r := range authz.Roles() {
			if authz.Has(r, d.Name) {
				b.WriteString(" yes |")
			} else {
				b.WriteString(" |")
			}
		}
		b.WriteString("\n")
	}
	b.WriteString("\n## Operations\n\n")
	b.WriteString("Operations marked `public` need no session. Operations marked `platform admin` are decided by the platform administrator flag, not by an organization role.\n\n")
	b.WriteString("| Operation | Request | Permission |\n|---|---|---|\n")
	for _, o := range ops {
		p, ok := authz.PermissionOf(o.id)
		if !ok {
			t.Fatalf("%s has no permission", o.id)
		}
		label := "`" + string(p) + "`"
		switch p {
		case authz.NoSession:
			label = "`public`"
		case authz.PlatformAdmin:
			label = "`platform admin`"
		}
		fmt.Fprintf(&b, "| `%s` | `%s %s` | %s |\n", o.id, o.method, o.path, label)
	}
	return b.String()
}

func TestRolesDoc(t *testing.T) {
	want := rolesDoc(t)
	if *updateRolesDoc {
		if err := os.WriteFile(rolesDocPath, []byte(want), 0o644); err != nil { //nolint:gosec // G306: a public document
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(rolesDocPath)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != want {
		t.Fatal("docs/roles.md is stale; run `go test ./internal/api -run TestRolesDoc -update` in backend/")
	}
}
